DROP TABLE IF EXISTS audit_log CASCADE;
DROP TABLE IF EXISTS trips CASCADE;
DROP TABLE IF EXISTS dtc_events CASCADE;
DROP TABLE IF EXISTS vehicle_ecus CASCADE;
DROP TABLE IF EXISTS warranty_claims CASCADE;
DROP TABLE IF EXISTS telemetry_events CASCADE;
DROP TABLE IF EXISTS ota_campaigns CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS vehicles CASCADE;
DROP TABLE IF EXISTS fleets CASCADE;

CREATE TABLE fleets (
  id SERIAL PRIMARY KEY,
  fleet_id VARCHAR(20) UNIQUE NOT NULL,
  name VARCHAR(100),
  owner_company VARCHAR(100),
  region VARCHAR(50),
  vehicle_count INTEGER,
  created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE vehicles (
  id SERIAL PRIMARY KEY,
  vin VARCHAR(17) UNIQUE NOT NULL,
  make VARCHAR(50),
  model VARCHAR(50),
  year INTEGER,
  fleet_id INTEGER,
  firmware_version VARCHAR(20),
  firmware_status VARCHAR(30) DEFAULT 'UP_TO_DATE',
  last_telemetry_at TIMESTAMP,
  created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE orders (
  id SERIAL PRIMARY KEY,
  order_id VARCHAR(20) UNIQUE NOT NULL,
  dealer_code VARCHAR(10),
  vehicle_vin VARCHAR(17),
  order_type VARCHAR(30),
  status VARCHAR(20) DEFAULT 'PENDING',
  total_amount DECIMAL(10,2),
  created_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE ota_campaigns (
  id SERIAL PRIMARY KEY,
  campaign_id VARCHAR(30) UNIQUE NOT NULL,
  firmware_version VARCHAR(20),
  target_ecu VARCHAR(30),
  target_fleet_id VARCHAR(20),
  status VARCHAR(20) DEFAULT 'PENDING',
  total_vehicles INTEGER,
  completed_vehicles INTEGER DEFAULT 0,
  failed_vehicles INTEGER DEFAULT 0,
  created_at TIMESTAMP DEFAULT NOW(),
  started_at TIMESTAMP,
  completed_at TIMESTAMP
);

CREATE TABLE telemetry_events (
  id SERIAL PRIMARY KEY,
  vehicle_vin VARCHAR(17) NOT NULL,
  event_type VARCHAR(30),
  latitude DECIMAL(9,6),
  longitude DECIMAL(9,6),
  speed_kmh INTEGER,
  soc_pct DECIMAL(5,2),
  fuel_level_pct DECIMAL(5,2),
  cell_voltage_min DECIMAL(4,2),
  cell_voltage_max DECIMAL(4,2),
  tire_pressure_fl DECIMAL(4,1),
  tire_pressure_fr DECIMAL(4,1),
  tire_pressure_rl DECIMAL(4,1),
  tire_pressure_rr DECIMAL(4,1),
  ambient_temp_c DECIMAL(4,1),
  engine_temp_c DECIMAL(5,1),
  odometer_km INTEGER,
  event_timestamp TIMESTAMP DEFAULT NOW()
);

CREATE TABLE warranty_claims (
  id SERIAL PRIMARY KEY,
  claim_id VARCHAR(20) UNIQUE NOT NULL,
  vehicle_vin VARCHAR(17),
  dealer_code VARCHAR(10),
  claim_type VARCHAR(30),
  description TEXT,
  status VARCHAR(20) DEFAULT 'OPEN',
  amount DECIMAL(10,2),
  filed_at TIMESTAMP DEFAULT NOW(),
  resolved_at TIMESTAMP
);

CREATE TABLE vehicle_ecus (
  id SERIAL PRIMARY KEY,
  vehicle_vin VARCHAR(17) NOT NULL,
  ecu_type VARCHAR(30) NOT NULL,
  hw_part_number VARCHAR(30),
  hw_revision VARCHAR(10),
  sw_version VARCHAR(30),
  sw_status VARCHAR(30) DEFAULT 'UP_TO_DATE',
  last_updated_at TIMESTAMP,
  installed_at TIMESTAMP DEFAULT NOW()
);

CREATE TABLE dtc_events (
  id SERIAL PRIMARY KEY,
  vehicle_vin VARCHAR(17) NOT NULL,
  dtc_code VARCHAR(10) NOT NULL,
  dtc_description VARCHAR(200),
  severity VARCHAR(10),
  ecu_source VARCHAR(30),
  status VARCHAR(20) DEFAULT 'ACTIVE',
  occurrence_count INTEGER DEFAULT 1,
  first_seen_at TIMESTAMP,
  last_seen_at TIMESTAMP,
  cleared_at TIMESTAMP
);

CREATE TABLE trips (
  id SERIAL PRIMARY KEY,
  trip_id VARCHAR(30) UNIQUE NOT NULL,
  vehicle_vin VARCHAR(17) NOT NULL,
  start_time TIMESTAMP NOT NULL,
  end_time TIMESTAMP,
  start_lat DECIMAL(9,6),
  start_lon DECIMAL(9,6),
  end_lat DECIMAL(9,6),
  end_lon DECIMAL(9,6),
  distance_km DECIMAL(8,2),
  duration_minutes INTEGER,
  avg_speed_kmh DECIMAL(5,1),
  max_speed_kmh INTEGER,
  energy_consumed_kwh DECIMAL(6,2),
  fuel_consumed_liters DECIMAL(5,2),
  start_soc_pct DECIMAL(5,2),
  end_soc_pct DECIMAL(5,2),
  harsh_braking_count INTEGER DEFAULT 0,
  harsh_acceleration_count INTEGER DEFAULT 0,
  idle_duration_minutes INTEGER DEFAULT 0
);

CREATE TABLE audit_log (
  id SERIAL PRIMARY KEY,
  action VARCHAR(50) NOT NULL,
  actor VARCHAR(100),
  resource_type VARCHAR(50),
  resource_id VARCHAR(50),
  details JSONB,
  created_at TIMESTAMP DEFAULT NOW()
);

